/**
 * Turns the official logo SVGs in public/brand into an inline <symbol> sprite.
 * The paths are copied untouched; only the two brand inks are swapped for CSS
 * variables (--logo-ink, --logo-plus) so the same mark switches navy/white per theme.
 * Output: src/components/ui/logo-sprite.tsx. Run with `pnpm logos` when the logo files change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');

const sources = [
  { id: 'mp-logo', file: 'MaamulPlus-Logo-v2.svg' },
  { id: 'mp-logo-notagline', file: 'MaamulPlus-Logo-NoTagline.svg' },
] as const;

const INK = /#0B2463/gi;
const PLUS = /#16A765/gi;

function toSymbol(id: string, svg: string): { viewBox: string; inner: string } {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const inner = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1];
  if (!viewBox || !inner) throw new Error(`Cannot parse ${id}`);
  const body = inner
    .replace(/<title>[\s\S]*?<\/title>/, '')
    .replace(/(fill|stroke)="(#[0-9a-f]{6})"/gi, (_m, attr: string, hex: string) => {
      const v = INK.test(hex) ? 'var(--logo-ink)' : PLUS.test(hex) ? 'var(--logo-plus)' : hex;
      INK.lastIndex = 0;
      PLUS.lastIndex = 0;
      return `style="${attr}:${v}"`;
    });
  return { viewBox, inner: body };
}

const symbols = sources.map(({ id, file }) => {
  const svg = readFileSync(resolve(root, 'public/brand', file), 'utf8');
  const { viewBox, inner } = toSymbol(id, svg);
  return { id, viewBox, markup: `<symbol id="${id}" viewBox="${viewBox}">${inner}</symbol>` };
});

const out = `/* Generated by scripts/build-logos.ts from public/brand. Do not edit. */
export const LOGO_VIEWBOX = {
${symbols.map((s) => `  '${s.id}': '${s.viewBox}',`).join('\n')}
} as const;

export type LogoSymbolId = keyof typeof LOGO_VIEWBOX;

const SPRITE = ${JSON.stringify(symbols.map((s) => s.markup).join(''))};

/** Rendered once in the root layout; every <Logo> references it with <use>. */
export function LogoSprite() {
  return (
    <svg width="0" height="0" style={{ position: 'absolute' }} aria-hidden="true" focusable="false">
      <defs dangerouslySetInnerHTML={{ __html: SPRITE }} />
    </svg>
  );
}
`;

writeFileSync(resolve(root, 'src/components/ui/logo-sprite.tsx'), out);
console.log('logo-sprite.tsx written');
