/**
 * Generates src/styles/tokens.css from design-system/tokens.json.
 * Runs before `dev` and `build`. Never edit tokens.css by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

type ThemedValue = string | { light: string; dark: string };
interface Token {
  name: string;
  value: ThemedValue;
}
interface TypeStyle {
  name: string;
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing?: string;
}
interface Tokens {
  color: { tokens: Token[] };
  type: {
    families: Record<string, string>;
    groups: { name: string; family: string; styles: TypeStyle[] }[];
  };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  shadow: { tokens: Token[] };
}

const root = resolve(import.meta.dirname, '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design-system/tokens.json'), 'utf8')) as Tokens;

// next/font exposes the self-hosted families as these variables (see src/app/fonts.ts).
const fontVars: Record<string, string> = { display: '--font-dm-sans', sans: '--font-inter' };

const light: string[] = [];
const dark: string[] = [];

function add(name: string, value: ThemedValue): void {
  if (typeof value === 'string') {
    light.push(`  --${name}: ${value};`);
  } else {
    light.push(`  --${name}: ${value.light};`);
    dark.push(`  --${name}: ${value.dark};`);
  }
}

for (const t of tokens.color.tokens) add(t.name, t.value);
for (const t of tokens.shadow.tokens) add(t.name, t.value);
for (const t of tokens.spacing.tokens) add(t.name, t.value);
for (const t of tokens.radius.tokens) add(t.name, t.value);

for (const [family, stack] of Object.entries(tokens.type.families)) {
  const v = fontVars[family];
  light.push(`  --font-${family}: ${v ? `var(${v}), ` : ''}${stack};`);
}

for (const group of tokens.type.groups) {
  for (const s of group.styles) {
    light.push(`  --text-${s.name}-size: ${s.fontSize};`);
    light.push(`  --text-${s.name}-line: ${s.lineHeight};`);
    light.push(`  --text-${s.name}-weight: ${s.fontWeight};`);
    light.push(`  --text-${s.name}-tracking: ${s.letterSpacing ?? 'normal'};`);
    light.push(`  --text-${s.name}-family: var(--font-${group.family});`);
  }
}

// Tailwind v4 theme: semantic colours, radii, shadows and fonts as utilities (bg-surface, text-heading, …).
const themeLines: string[] = [];
for (const t of tokens.color.tokens) themeLines.push(`  --color-${t.name}: var(--${t.name});`);
for (const t of tokens.radius.tokens) themeLines.push(`  --${t.name}: var(--${t.name});`);
for (const t of tokens.shadow.tokens) themeLines.push(`  --${t.name}: var(--${t.name});`);
themeLines.push('  --font-display: var(--font-display);', '  --font-sans: var(--font-sans);', '  --font-mono: var(--font-mono);');

const typeUtilities = tokens.type.groups
  .flatMap((g) => g.styles)
  .map(
    (s) =>
      `@utility type-${s.name} {\n  font-family: var(--text-${s.name}-family);\n  font-size: var(--text-${s.name}-size);\n  line-height: var(--text-${s.name}-line);\n  font-weight: var(--text-${s.name}-weight);\n  letter-spacing: var(--text-${s.name}-tracking);\n}`,
  )
  .join('\n');

const css = `/* Generated by scripts/build-tokens.ts from design-system/tokens.json. Do not edit. */
:root {
${light.join('\n')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not(.light) {
${dark.map((l) => '  ' + l).join('\n')}
    color-scheme: dark;
  }
}
:root.dark {
${dark.join('\n')}
  color-scheme: dark;
}

@theme inline {
${themeLines.join('\n')}
}

${typeUtilities}
`;

writeFileSync(resolve(root, 'src/styles/tokens.css'), css);
console.log('tokens.css written');
